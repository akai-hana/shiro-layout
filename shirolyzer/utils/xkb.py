"""Generate XKB symbols files from a 30-character layout string.

The layout string uses QWERTY physical positions in row-major order: the top
row, the home row, then the bottom row.  Letters map to themselves and the
punctuation keys keep the symbols used by ``xkb/mine``.  The apostrophe is
kept on both the ANSI key to the right of the home row and the optional ISO
key (``<LSGT>``), matching the shipped symbols file.
"""
from __future__ import annotations

import hashlib
from pathlib import Path

from . import paths

ROWS = ("QWERTYUIOP", "ASDFGHJKL;", "ZXCVBNM,./")
LAYOUT_LENGTH = 30
LETTERS = "abcdefghijklmnopqrstuvwxyz"

KEYCODE = {
    key: f"{prefix}{column:02d}"
    for row, prefix in zip(ROWS, ("AD", "AC", "AB"))
    for column, key in enumerate(row, 1)
}

SYMBOLS = {
    ";": ("semicolon", "colon"),
    ",": ("comma", "less"),
    ".": ("period", "greater"),
    "/": ("slash", "question"),
    "'": ("apostrophe", "quotedbl"),
    "-": ("minus", "underscore"),
    "=": ("equal", "plus"),
    "[": ("bracketleft", "braceleft"),
    "]": ("bracketright", "braceright"),
    "\\": ("backslash", "bar"),
    "`": ("grave", "asciitilde"),
}

EXTRA_KEYS = (
    ("AC11", ("apostrophe", "quotedbl")),
    ("LSGT", ("apostrophe", "quotedbl")),
)


def _normalise_layout(layout):
    layout = str(layout)
    if len(layout) != LAYOUT_LENGTH:
        raise ValueError(
            f"layout must be {LAYOUT_LENGTH} characters, got {len(layout)}")
    layout = layout.lower()
    for char in layout:
        if char not in SYMBOLS and char not in LETTERS:
            raise ValueError(f"unsupported layout character: {char!r}")
    if len(set(layout)) != LAYOUT_LENGTH:
        raise ValueError("layout contains duplicate characters")
    missing = sorted(set(LETTERS) - set(layout))
    if missing:
        raise ValueError(f"layout is missing letters: {''.join(missing)}")
    return layout


def _symbols_for(char):
    if char in SYMBOLS:
        return SYMBOLS[char]
    return char, char.upper()


def _grid(layout):
    return [layout[0:10], layout[10:20], layout[20:30]]


def safe_name(layout):
    """Return a filesystem-friendly name that never collides with ``mine``."""
    digest = hashlib.sha1(_normalise_layout(layout).encode("ascii")).hexdigest()
    return f"shiro_{digest[:8]}"


def symbols(layout, name="shiro"):
    """Return the XKB symbols text for ``layout``.

    The body is intentionally identical to the shipped ``xkb/mine`` file; only
    the header comments and the group name depend on the supplied name.
    """
    layout = _normalise_layout(layout)
    name = str(name).strip()
    if not name:
        raise ValueError("layout name must not be empty")
    rows = _grid(layout)
    lines = [
        f"// {name} layout — generated by shirolyzer",
        f"// top:  {' '.join(rows[0][:5])}  {' '.join(rows[0][5:])}",
        f"// home: {' '.join(rows[1][:5])}  {' '.join(rows[1][5:])}",
        f"// bot:  {' '.join(rows[2][:5])}  {' '.join(rows[2][5:])}",
        "partial alphanumeric_keys",
        'xkb_symbols "basic" {',
        f'    name[Group1] = "{name}";',
        "",
        '    include "us(basic)"',
        "",
    ]
    for row_index, row in enumerate(rows):
        for column, char in enumerate(row):
            key = ROWS[row_index][column]
            base, shift = _symbols_for(char)
            lines.append(
                f"    key <{KEYCODE[key]}> {{ [ {base + ',':<13}{shift:<9} ] }};")
        lines.append("")
    for keycode, (base, shift) in EXTRA_KEYS:
        lines.append(
            f"    key <{keycode}> {{ [ {base + ',':<13}{shift:<9} ] }};")
    lines.extend(["};", ""])
    return "\n".join(lines)


def write(path, layout, name="shiro"):
    """Write generated symbols to ``path`` and return the path."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(symbols(layout, name), encoding="utf-8")
    return path


def write_named(layout, name=None, directory=None):
    """Write a layout under ``xkb/`` using ``name`` or a generated safe name."""
    name = name or safe_name(layout)
    directory = Path(directory) if directory is not None else paths.XKB_DIR
    return write(directory / name, layout, name)
